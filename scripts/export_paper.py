# ---------------------------------------------------------------- formatting
def num(x, d=2, sign=True) -> str:
    if x is None or (isinstance(x, float) and (math.isnan(x) or math.isinf(x))):
        return PENDING
    s = f"{x:+.{d}f}" if sign else f"{x:.{d}f}"
    return "$" + s.replace("-", "-") + "$"


def pct(x, d=1) -> str:
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return PENDING
    return f"${x * 100:+.{d}f}\\%$" if x < 0 else f"${x * 100:.{d}f}\\%$"


def pval(p) -> str:
    if p is None or (isinstance(p, float) and math.isnan(p)):
        return PENDING
    return "$<0.001$" if p < 0.001 else f"${p:.3f}$"


def plain(x, d=2) -> str:
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return PENDING
    return f"{x:.{d}f}"


def interval(lo, hi, d=2) -> str:
    if any(v is None or (isinstance(v, float) and math.isnan(v)) for v in (lo, hi)):
        return PENDING
    return f"$[{lo:.{d}f},\\,{hi:.{d}f}]$"


class Numbers:
    def __init__(self):
        self.tex: dict[str, str] = {}
        self.raw: dict[str, object] = {}

    def set(self, key: str, tex: str, raw=None):
        self.tex[key] = tex
        self.raw[key] = raw

    def write(self, path: Path):
        lines = ["% generated by scripts/export_paper.py -- do not edit"]
        for k in sorted(self.tex):
            lines.append(f"\\pactdef{{{k}}}{{{self.tex[k]}}}")
        path.write_text("\n".join(lines) + "\n")


# ---------------------------------------------------------------- loading
def load_cell(cell_id: str, missing: list[str]) -> dict | None:
    d = RAW_DIR / cell_id
    if not (d / "metadata.json").exists():
        missing.append(cell_id)
        return None
    try:
        c = load_backtest_result(d)
    except ValueError as e:
        log.warning("%s", e)
        missing.append(f"{cell_id} (pre-fix schema; rerun)")
        return None
    # A cell whose LLM calls failed (API errors, unparseable output) silently
    # falls back to neutral views; above 1% of calls it is not a valid result.
    meta = c.get("metadata", {})
    stats = meta.get("llm_stats") or {}
    n_calls = sum(v for k, v in stats.items() if k.endswith(":calls"))
    n_fail = max(int(meta.get("agent_failure_total", 0)),
                 sum(v for k, v in stats.items() if k.endswith((":call_failed", ":unparseable"))))
    if n_calls and n_fail / n_calls > MAX_FAILURE_RATE:
        log.warning("%s: %d of %d LLM calls failed; treated as missing", cell_id, n_fail, n_calls)
        missing.append(f"{cell_id} ({n_fail}/{n_calls} LLM calls failed; rerun)")
        return None
    c["excess_returns"] = c["excess_returns"].loc[str(START):str(END)]
    c["gross_excess_returns"] = c["gross_excess_returns"].loc[str(START):str(END)]
    return c


def stats_for(excess: pd.Series, total: pd.Series, equity: pd.Series, turnover: pd.Series) -> dict:
    lo, hi = sharpe_bootstrap_ci(excess)
    return {
        "sr": sharpe(excess), "sortino": sortino(excess), "mdd": max_drawdown(equity),
        "ann_ret": annualized_return(total), "turnover": annual_turnover(turnover),
        "ci_lo": lo, "ci_hi": hi,
        "sr_h1": sharpe(excess[excess.index < SPLIT]), "sr_h2": sharpe(excess[excess.index >= SPLIT]),
    }


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="results/paper_tex")
    ap.add_argument("--loo-cell", default="b__frontier__sequential_pipeline")
    args = ap.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    N = Numbers()
    missing: list[str] = []

    # ---------------- cells
    cells: dict[tuple[str, str], dict] = {}
    det = load_cell(f"{WINDOW}__none__deterministic_only", missing)
    for reg in REGIMES:
        for p in PROTOCOLS:
            if reg == "none" and p == "single_agent":
                continue          # undefined without an LLM
            if reg == "none" and p == "llm_plus_anchor":
                continue          # identical to the deterministic baseline by construction
            c = load_cell(f"{WINDOW}__{reg}__{p}", missing)
            if c is not None:
                cells[(reg, p)] = c
    if det is not None:
        cells[("none", "deterministic_only")] = det
        cells[("none", "llm_plus_anchor")] = det

    st = {k: stats_for(c["excess_returns"], c["returns"], c["equity"], c["turnover"]) for k, c in cells.items()}

    # ---------------- benchmarks
    universe = None
    for c in cells.values():
        universe = list(c["metadata"]["universe"])
        break
    if universe is None:
        from data.universe import TRADEABLE_SYMBOLS
        universe = list(TRADEABLE_SYMBOLS)
    bench = compute_benchmarks(universe, START, END)
    bst = {k: stats_for(r.excess_returns, r.total_returns, r.equity, r.turnover) for k, r in bench.items()}
    bench_tc = {}
    for tc in TC_GRID:
        res = compute_benchmarks(universe, START, END, cost_bps_roundtrip=float(tc))
        bench_tc[tc] = {k: sharpe(r.excess_returns) for k, r in res.items()}

    def sr(reg, p):
        return st.get((reg, p), {}).get("sr", float("nan"))

    # ---------------- per-cell numbers
    for (reg, p), s in st.items():
        tag = f"{reg}.{p}".replace("_", "")
        for k in ("sr", "sortino", "ci_lo", "ci_hi", "sr_h1", "sr_h2"):
            N.set(f"{tag}.{k.replace('_', '')}", num(s[k]), s[k])
        N.set(f"{tag}.mdd", pct(s["mdd"]), s["mdd"])
        N.set(f"{tag}.annret", pct(s["ann_ret"]), s["ann_ret"])
        N.set(f"{tag}.turnover", plain(s["turnover"], 1), s["turnover"])
    for k, s in bst.items():
        tag = f"bench.{k.replace('_', '')}"
        for m in ("sr", "sortino", "sr_h1", "sr_h2"):
            N.set(f"{tag}.{m.replace('_', '')}", num(s[m]), s[m])
        N.set(f"{tag}.mdd", pct(s["mdd"]), s["mdd"])
        N.set(f"{tag}.annret", pct(s["ann_ret"]), s["ann_ret"])

    # ---------------- Table: headline matrix
    rows = []
    for p in PROTOCOLS + ("deterministic_only",):
        if p == "deterministic_only":
            s_none = st.get(("none", p), {})
            rows.append(
                r"\midrule " + f"{LABEL[p]} & {num(s_none.get('sr'))} & \\multicolumn{{2}}{{c}}{{(no LLM)}} & "
                f"{plain(s_none.get('turnover'), 1)} & {pct(s_none.get('mdd'))} \\\\"
            )
            continue
        a = st.get(("none", p), {})
        b = st.get(("frontier", p), {})
        none_cell = "n/a" if p == "single_agent" else (
            r"\textit{=det.}" if p == "llm_plus_anchor" else num(a.get("sr")))
        delta = (b.get("sr", float("nan")) - a.get("sr", float("nan"))) if p != "single_agent" else float("nan")
        ci = interval(b.get("ci_lo", float("nan")), b.get("ci_hi", float("nan"))) if b else PENDING
        rows.append(
            f"{LABEL[p]} & {none_cell} & {num(b.get('sr'))} {{\\scriptsize {ci}}} & "
            f"{'n/a' if p == 'single_agent' else num(delta)} & {plain(b.get('turnover'), 1)} & {pct(b.get('mdd'))} \\\\"
        )
    (out / "tab_matrix.tex").write_text("\n".join(rows) + "\n")

    # ---------------- Table: benchmarks vs strategies
    brow = []
    for k in ("spy_bh", "equal_weight", "sixty_forty", "inverse_vol"):
        s = bst[k]
        brow.append(f"{BENCHMARK_LABELS[k]} & {num(s['sr'])} & {num(s['sortino'])} & {pct(s['mdd'])} & "
                    f"{pct(s['ann_ret'])} \\\\")
    s = st.get(("none", "deterministic_only"), {})
    brow.append(r"\midrule " + f"Deterministic baseline & {num(s.get('sr'))} & {num(s.get('sortino'))} & "
                f"{pct(s.get('mdd'))} & {pct(s.get('ann_ret'))} \\\\")
    llm_cells = {p: st[("frontier", p)] for p in PROTOCOLS if ("frontier", p) in st}
    best_llm = max(llm_cells, key=lambda p: llm_cells[p]["sr"]) if llm_cells else None
    if best_llm:
        s = llm_cells[best_llm]
        brow.append(f"Best Claude cell ({SHORT[best_llm]}) & {num(s['sr'])} & {num(s['sortino'])} & "
                    f"{pct(s['mdd'])} & {pct(s['ann_ret'])} \\\\")
    else:
        brow.append(f"Best Claude cell & {PENDING} & {PENDING} & {PENDING} & {PENDING} \\\\")
    (out / "tab_bench.tex").write_text("\n".join(brow) + "\n")
    N.set("best.llm.name", SHORT[best_llm] if best_llm else PENDING, best_llm)
    N.set("best.llm.sr", num(llm_cells[best_llm]["sr"]) if best_llm else PENDING)
    best_bench = max(bst, key=lambda k: bst[k]["sr"])
    N.set("best.bench.name", BENCH_SHORT[best_bench], best_bench)
    N.set("best.bench.sr", num(bst[best_bench]["sr"]), bst[best_bench]["sr"])
    det_sr = sr("none", "deterministic_only")
    n_bench_beaten_det = sum(1 for k in bst if not math.isnan(det_sr) and det_sr > bst[k]["sr"])
    N.set("det.nbenchbeaten", str(n_bench_beaten_det) if not math.isnan(det_sr) else PENDING, n_bench_beaten_det)
    if llm_cells:
        n_llm_above_best_bench = sum(1 for p in llm_cells if llm_cells[p]["sr"] > bst[best_bench]["sr"])
        n_llm_above_det = sum(1 for p in llm_cells if llm_cells[p]["sr"] > det_sr)
        N.set("llm.naboveBestBench", str(n_llm_above_best_bench), n_llm_above_best_bench)
        N.set("llm.naboveDet", str(n_llm_above_det), n_llm_above_det)
        N.set("llm.ncells", str(len(llm_cells)), len(llm_cells))
        srs = [llm_cells[p]["sr"] for p in llm_cells]
        N.set("llm.spread", plain(max(srs) - min(srs)), max(srs) - min(srs))
    else:
        for k in ("llm.naboveBestBench", "llm.naboveDet", "llm.ncells", "llm.spread"):
            N.set(k, PENDING)

    # ---------------- H1 and tests
    def series(key):
        if key in bench:
            return bench[key].excess_returns
        reg, p = key
        return cells[(reg, p)]["excess_returns"] if (reg, p) in cells else None

    def gross(reg, p):
        return cells[(reg, p)]["gross_excess_returns"] if (reg, p) in cells else None

    tests = []
    for p in COORDINATED:
        tests.append((f"H1: {SHORT[p]} vs ensemble (Claude)", ("frontier", p), ("frontier", "independent_ensemble")))
    tests.append(("Monolith vs ensemble (Claude)", ("frontier", "single_agent"), ("frontier", "independent_ensemble")))
    for bk, bl in (("spy_bh", "SPY buy-and-hold"), ("equal_weight", "equal weight"),
                   ("sixty_forty", "60/40"), ("inverse_vol", "inverse volatility")):
        tests.append((f"Deterministic vs {bl}", ("none", "deterministic_only"), bk))
    if best_llm:
        tests.append((f"Best Claude ({SHORT[best_llm]}) vs deterministic", ("frontier", best_llm), ("none", "deterministic_only")))
        tests.append((f"Best Claude ({SHORT[best_llm]}) vs {BENCHMARK_LABELS[best_bench].split(' (')[0].lower()}",
                      ("frontier", best_llm), best_bench))
    else:
        tests.append(("Best Claude vs deterministic", None, None))
        tests.append(("Best Claude vs best benchmark", None, None))
    for p in ("independent_ensemble", "sequential_pipeline", "hierarchical", "debate"):
        tests.append((f"Claude vs no LLM: {SHORT[p]}", ("frontier", p), ("none", p)))

    results = []
    for label, a, b in tests:
        ra = series(a) if a is not None else None
        rb = series(b) if b is not None else None
        if ra is None or rb is None:
            results.append({"label": label, "available": False})
            continue
        lw = ledoit_wolf_sharpe_test(ra, rb)
        bs = paired_bootstrap_sharpe_diff(ra, rb)
        results.append({"label": label, "available": True, **lw, "bs_lo": bs["ci_lo"], "bs_hi": bs["ci_hi"],
                        "bs_p": bs["p_value"]})
    avail = [r for r in results if r["available"] and not math.isnan(r["p_value"])]
    family_complete = len(avail) == len(results)
    if family_complete:   # BH over the full planned family only; otherwise q is pending
        for r, q in zip(avail, bh_qvalues([r["p_value"] for r in avail])):
            r["q"] = q
    else:
        missing.append("test family incomplete: q-values pending")
    trow = []
    for r in results:
        if not r["available"]:
            trow.append(f"{r['label']} & {PENDING} & {PENDING} & {PENDING} & {PENDING} \\\\")
            continue
        trow.append(f"{r['label']} & {num(r['sr_diff'])} & {num(r['z'])} & {pval(r.get('q', float('nan')))} & "
                    f"{interval(r['bs_lo'], r['bs_hi'])} \\\\")
    (out / "tab_tests.tex").write_text("\n".join(trow) + "\n")
    N.set("tests.n", str(len(results)), len(results))
    N.set("tests.nsig", str(sum(1 for r in avail if r.get("q", 1) < 0.05)) if family_complete else PENDING)

    h1 = [r for r in results if r["label"].startswith("H1") and r["available"]]
    if len(h1) == len(COORDINATED) and family_complete:
        n_better = sum(1 for r in h1 if r["sr_diff"] > 0)
        n_sig_better = sum(1 for r in h1 if r["sr_diff"] > 0 and r.get("q", 1) < 0.05)
        n_sig_worse = sum(1 for r in h1 if r["sr_diff"] < 0 and r.get("q", 1) < 0.05)
        verdict = ("supported" if n_sig_better >= 1 and n_sig_worse == 0 else
                   "contradicted" if n_sig_worse >= 1 and n_sig_better == 0 else
                   "only partly supported" if n_sig_better >= 1 else "not supported")
        N.set("hone.nbetter", str(n_better), n_better)
        N.set("hone.nsigbetter", str(n_sig_better), n_sig_better)
        N.set("hone.nsigworse", str(n_sig_worse), n_sig_worse)
        N.set("hone.verdict", verdict, verdict)
    else:
        for k in ("hone.nbetter", "hone.nsigbetter", "hone.nsigworse", "hone.verdict"):
            N.set(k, PENDING)
    for r in results:
        if r["available"]:
            key = "test." + "".join(ch for ch in r["label"].lower() if ch.isalnum())[:40]
            N.set(key + ".diff", num(r["sr_diff"]), r["sr_diff"])
            N.set(key + ".q", pval(r.get("q", float("nan"))), r.get("q"))

    # ---------------- CBS (H2)
    cbs_rows = {}
    for reg in REGIMES:
        for p in COORDINATED:
            if reg == "none" and p == "llm_plus_anchor":
                continue
            gc, ge = gross(reg, p), gross(reg, "independent_ensemble")
            if gc is None or ge is None:
                cbs_rows[(reg, p)] = float("nan")
                continue
            cbs_rows[(reg, p)] = coordination_breakeven_spread(
                gc, ge, cells[(reg, p)]["turnover"], cells[(reg, "independent_ensemble")]["turnover"])
    for (reg, p), v in cbs_rows.items():
        tag = f"cbs.{reg}.{p.replace('_', '')}"
        if math.isnan(v):
            have = (reg, p) in cells and (reg, "independent_ensemble") in cells
            N.set(tag, r"$>$400" if have else PENDING, v)
        else:
            N.set(tag, f"{v:.0f}", v)
    fr = [cbs_rows.get(("frontier", p), float("nan")) for p in COORDINATED]
    have_fr = all(("frontier", p) in cells for p in COORDINATED + ("independent_ensemble",))
    if have_fr:
        vals = [400.0 if math.isnan(x) else x for x in fr]
        N.set("cbs.frontier.max", f"{max(vals):.0f}", max(vals))
        n50 = sum(1 for v in vals if v > 50)
        N.set("htwo.n", str(n50), n50)
        N.set("htwo.verdict", "met" if n50 >= 1 else "not met")
    else:
        for k in ("cbs.frontier.max", "htwo.n", "htwo.verdict"):
            N.set(k, PENDING)

    # ---------------- cost sensitivity figure + per-cell numbers
    tc_table = {}
    for (reg, p), c in cells.items():
        if (reg, p) == ("none", "llm_plus_anchor"):
            continue
        tc_table[(reg, p)] = {tc: sharpe(net_excess_at_cost(c["gross_excess_returns"], c["turnover"], tc))
                              for tc in TC_GRID}
    for (reg, p), d in tc_table.items():
        for tc, v in d.items():
            N.set(f"tc.{reg}.{p.replace('_', '')}.{tc}", num(v), v)
    for k, d in ((k, {tc: bench_tc[tc][k] for tc in TC_GRID}) for k in bst):
        for tc, v in d.items():
            N.set(f"tc.bench.{k.replace('_', '')}.{tc}", num(v), v)
    _plot_cost(out / "fig_cost.pdf", tc_table, bench_tc)

    # ---------------- LOO (H4)
    loo_path = TABLES_DIR / "attribution_loo.csv"
    lrow = []
    loo_ok = False
    if loo_path.exists():
        loo = pd.read_csv(loo_path)
        loo = loo[(loo["cell_id"] == args.loo_cell)]
        if "schema_version" in loo.columns and len(loo) and int(loo["schema_version"].min()) >= 2:
            loo_ok = True
    if loo_ok:
        full = float(loo["sharpe_full"].iloc[0])
        N.set("loo.full", num(full), full)
        for a in AGENTS[:-1]:   # risk agent: no directional role, Delta = 0 by construction
            r = loo[loo["dropped_agent"] == a]
            if r.empty:
                lrow.append(f"{AGENT_LABEL[a]} & {PENDING} & {PENDING} \\\\")
                continue
            w, dlt = float(r["sharpe_without"].iloc[0]), float(r["sharpe_delta"].iloc[0])
            lrow.append(f"{AGENT_LABEL[a]} & {num(w)} & {num(dlt)} \\\\")
            N.set(f"loo.{a.replace('_', '')}", num(dlt), dlt)
        d = loo[loo["dropped_agent"] != "risk_correlation"].set_index("dropped_agent")["sharpe_delta"]
        N.set("loo.mostneg", AGENT_LABEL.get(d.idxmin(), d.idxmin()).lower(), d.idxmin())
        N.set("loo.mostnegval", num(float(d.min())), float(d.min()))
        N.set("loo.mostpos", AGENT_LABEL.get(d.idxmax(), d.idxmax()).lower(), d.idxmax())
        N.set("loo.mostposval", num(float(d.max())), float(d.max()))
        N.set("loo.nlarge", str(int((d.abs() >= 0.10).sum())), int((d.abs() >= 0.10).sum()))
        N.set("hfour.verdict", "met" if (d.abs() >= 0.10).any() else "not met")
    else:
        missing.append(f"{loo_path} for {args.loo_cell} (v2)")
        for a in AGENTS[:-1]:
            lrow.append(f"{AGENT_LABEL[a]} & {PENDING} & {PENDING} \\\\")
        for k in ("loo.full", "loo.mostneg", "loo.mostnegval", "loo.mostpos", "loo.mostposval", "loo.nlarge",
                  "hfour.verdict"):
            N.set(k, PENDING)
    (out / "tab_loo.tex").write_text("\n".join(lrow) + "\n")

    # ---------------- alt-data (H3)
    arow = []
    alt = {}
    for p in ("sequential_pipeline", "debate"):
        for v in ALT_VARIANTS:
            c = load_cell(f"altdata_{v}__{WINDOW}__frontier__{p}", missing)
            alt[(p, v)] = sharpe(c["excess_returns"]) if c is not None else float("nan")
    best_alt = (None, -np.inf)
    for v in ALT_VARIANTS:
        cols = []
        for p in ("sequential_pipeline", "debate"):
            base, val = alt[(p, "text_only")], alt[(p, v)]
            if v == "text_only":
                cols.append(num(val))
            else:
                dlt = val - base
                cols.append(num(dlt))
                if not math.isnan(dlt) and dlt > best_alt[1]:
                    best_alt = ((p, v), dlt)
                N.set(f"alt.{p.replace('_', '')}.{v.replace('_', '')}", num(dlt), dlt)
        arow.append(f"{ALT_LABEL[v]} & " + " & ".join(cols) + " \\\\")
    (out / "tab_altdata.tex").write_text("\n".join(arow) + "\n")
    ev = [alt.get((p, "plus_attention"), float("nan")) - alt.get((p, "text_only"), float("nan"))
          for p in ("sequential_pipeline", "debate")]
    if not any(math.isnan(x) for x in ev):
        n_ok = sum(1 for x in ev if x >= 0.05)
        N.set("hthree.verdict", "met" if n_ok == 2 else ("met for one of the two protocols" if n_ok == 1 else "not met"))
    else:
        N.set("hthree.verdict", PENDING)
    if best_alt[0]:
        N.set("alt.best", {"plus_attention": "attention features (Wikipedia, Google Trends)",
                           "plus_instrument": "instrument-specific data",
                           "full": "attention plus instrument-specific data"}[best_alt[0][1]],
              best_alt[0][1])
        N.set("alt.bestval", num(best_alt[1]), best_alt[1])
    else:
        N.set("alt.best", PENDING)
        N.set("alt.bestval", PENDING)

    # ---------------- implementation audit
    audit_path = TABLES_DIR / "pitfall_audit.json"
    arows = []
    prefix_path = TABLES_DIR / "pitfall_audit_prefix.json"
    if audit_path.exists():
        audit = json.loads(audit_path.read_text())
        audit = [r for r in audit if r["label"] != "prefix_code"]
        if prefix_path.exists():
            audit.append(json.loads(prefix_path.read_text()))
        else:
            missing.append(str(prefix_path))
        fixed = next(r for r in audit if r["label"] == "fixed")
        for r in audit:
            N.set(f"audit.{r['label'].replace('_', '')}.sr", num(r["sharpe"]), r["sharpe"])
            if r["label"] != "fixed":
                N.set(f"audit.{r['label'].replace('_', '')}.delta", num(r["sharpe"] - fixed["sharpe"]),
                      r["sharpe"] - fixed["sharpe"])
            arows.append(r)
        harmful = [abs(r["sharpe"] - fixed["sharpe"]) for r in audit
                   if r["label"] in ("level_splice", "union_calendar", "double_cost", "no_warmup")]
        if harmful:
            N.set("audit.rangelo", plain(min(harmful)), min(harmful))
            N.set("audit.rangehi", plain(max(harmful)), max(harmful))
        rfz = next((r for r in audit if r["label"] == "rf_zero"), None)
        if rfz:
            N.set("audit.rfzero.absdelta", plain(abs(rfz["sharpe"] - fixed["sharpe"])),
                  abs(rfz["sharpe"] - fixed["sharpe"]))
    else:
        missing.append(str(audit_path))
    (out / "audit.json").write_text(json.dumps(arows, indent=2))

    # ---------------- LLM fallback reporting
    fb = []
    for (reg, p), c in cells.items():
        if reg != "frontier":
            continue
        stats = c["metadata"].get("llm_stats", {}) or {}
        calls = sum(v for k, v in stats.items() if k.endswith(":calls"))   # specialist + protocol-level
        fails = sum(v for k, v in stats.items() if k.endswith(":call_failed") or k.endswith(":unparseable"))
        prot_fail = int(c["metadata"].get("agent_failure_total", 0))
        fb.append((fails / calls if calls else 0.0, prot_fail))
    if fb:
        N.set("llm.fallbackmax", pct(max(x for x, _ in fb), 1), max(x for x, _ in fb))
        N.set("llm.protfailmax", str(max(y for _, y in fb)), max(y for _, y in fb))
    else:
        N.set("llm.fallbackmax", PENDING)
        N.set("llm.protfailmax", PENDING)
    det_meta = det["metadata"] if det is not None else {}
    N.set("det.rebalances", str(det_meta.get("rebalances", PENDING)), det_meta.get("rebalances"))
    N.set("det.ndays", str(len(det["excess_returns"])) if det is not None else PENDING)

    N.write(out / "numbers.tex")
    (out / "results.json").write_text(json.dumps(N.raw, indent=2, default=str))
    (out / "MISSING.txt").write_text("\n".join(sorted(set(missing))) + "\n")
    print(f"wrote {out}; {len(set(missing))} missing inputs (see MISSING.txt)")


